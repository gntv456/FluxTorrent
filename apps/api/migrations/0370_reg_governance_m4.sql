-- 隐私口径（与 registration-policy 一致）：reg_ip_signups 只存
-- sha3-256(ip) 的十六进制摘要，**不存明文 IP**；30 天后由 worker cron
-- 清理（保留期见 site_settings.reg_ip_retention_days）。

-- ① 同 IP 注册留痕（摘要制）
CREATE TABLE IF NOT EXISTS reg_ip_signups (
  id bigserial PRIMARY KEY,
  ip_hash text NOT NULL,
  user_id bigint,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_reg_ip_signups
  ON reg_ip_signups (ip_hash, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reg_ip_signups_created
  ON reg_ip_signups (created_at);

