-- 0432: reg_window 提示语升级（P-684/P-686 配套）。
--
-- reg_window 是开放注册轮的结构化配置（JSON 四字段），本批补齐：
--   · 名额口径：只数直接注册（invited_by IS NULL），邀请码注册不占名额
--   · 预约语义：open 可设未来时间——到点自动放行直接注册、close 到点
--     自动恢复邀请制（读时惰性判定，站长无须手动开关）
--   · 满额/到期自动关闭对外注册模式显示（登录页/注册页随动）
-- 提示语把这些语义写给站长，替代此前一句裸 JSON 说明。

UPDATE settings_meta
   SET hint = '开放注册轮配置，JSON 格式 {"open":"起","close":"止","slots":名额,"label":"轮名"}。open/close 为 RFC3339 时间可设未来=预约自动开放/到点自动关闭；slots=免邀请码名额（只数直接注册，邀请注册不占；0=不限），满额自动关闭开放；留空=不启用窗口。示例 {"open":"2026-11-01T08:00:00+08:00","close":"2026-11-03T08:00:00+08:00","slots":100,"label":"周年庆开放"}'
 WHERE name = 'reg_window';
