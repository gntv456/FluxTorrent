-- 0454: 标签字典不再存「空底 + 白字」这种自相矛盾的配色
--
-- `tag_dict.color` 的列默认值是 '#ffffff'，它预设「背后一定有底色」。可
-- 站型包导入路径（staff_http/pack_tags.rs）建标签时只写 name/kind/scope，
-- 底色与字色全落列默认 ⇒ 存进来就是「bg_color='' + color='#ffffff'」：
-- 后台「标签字典」列表与编辑预览、论坛标签芯片都是白字落在透明/浅底上，
-- 芯片框里连字都看不见（2026-11-02 站长在标签字典页看到的现象）。
-- 现网实测：9 条标签里 4 条是这个形状——官种（global，被 10 颗种引用）、
-- 合集 / 完结 / 官方（pack，即站型层）。也就是说**每个站型包带进来的标签**
-- 都是这个形状，不是某几条漏配。
--
-- 修法分两层，缺一层都会再犯：
--   · 渲染侧（apps/web/lib/tag-style.ts）定一条规矩「字色跟着底色走」，
--     没有底色就整套交回主题——这条保护的是**所有已存在的库**，包括
--     还没升级到本迁移的站点；
--   · 存库侧（本迁移）把矛盾值抹平，并把列默认改成空串：「没配色」应当
--     存成「什么都没写」，而不是存一个只在有底色时才对的白色。
-- 反向不处理：有底色而 color 为空是合法的（芯片惯例深底白字），回落白字
-- 由渲染侧负责。

ALTER TABLE tag_dict ALTER COLUMN color SET DEFAULT '';

UPDATE tag_dict
   SET color = ''
 WHERE COALESCE(bg_color, '') = ''
   AND COALESCE(color, '') <> '';
